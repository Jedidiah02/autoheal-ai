@demo_app.get("/dashboard", response_class=HTMLResponse)
async def dashboard_page(v: int = 1):
    """Post-login dashboard with checkout action."""
    button_html = (
        '<button id="pay-now-btn" data-testid="pay-button" class="btn-checkout" onclick="performCheckout()">Transfer $500</button>'
        if v == 1 else
        '<button id="healed-checkout-uuid-883" class="btn-confirm-action" data-test="pay-button" onclick="performCheckout()">Transfer $500</button>'
    )

    html = f"""<!DOCTYPE html>
    <html>
    <head>
      <title>FinSecure Dashboard</title>
      <style>
        body {{ font-family: sans-serif; background: #0b0f19; color: white; padding: 3rem; display: flex; justify-content: center; }}
        .panel {{ background: #161e2e; border: 1px solid #283548; padding: 2rem; border-radius: 1rem; max-width: 500px; width: 100%; }}
        .btn-checkout, .btn-confirm-action {{ background: #10b981; color: white; border: none; padding: 0.8rem 1.5rem; border-radius: 0.5rem; cursor: pointer; font-weight: bold; width: 100%; }}
        #status-msg {{ margin-top: 1rem; padding: 0.75rem; border-radius: 0.5rem; display: none; }}
      </style>
      <script>
        async function performCheckout() {{
          const urlParams = new URLSearchParams(window.location.search);
          const crash = urlParams.get('crash') === 'true';
          const endpoint = crash ? '/api/transfer?crash=true' : '/api/transfer';
          
          try {{
            const res = await fetch(endpoint, {{ method: 'POST' }});
            if (!res.ok) throw new Error("HTTP " + res.status);
            const data = await res.json();
            const msg = document.getElementById('status-msg');
            msg.style.display = 'block';
            msg.style.background = '#065f46';
            msg.innerText = "Transaction Approved: ID " + data.tx_id;
          }} catch (err) {{
            const msg = document.getElementById('status-msg');
            msg.style.display = 'block';
            msg.style.background = '#991b1b';
            msg.innerText = "Transaction Failed: " + err.message;
            console.error("Payment API Error:", err);
          }}
        }}
      </script>
    </head>
    <body>
      <div class="panel">
        <h2 id="welcome-header">Welcome, Account Holder</h2>
        <p>Available Balance: <strong>$12,450.00</strong></p>
        <div style="margin: 2rem 0;">
          {button_html}
        </div>
        <div id="status-msg"></div>
      </div>
    </body>
    </html>
    """
    return HTMLResponse(content=html)


@demo_app.post("/api/transfer")
async def api_transfer(crash: bool = False):
    """Simulates an API endpoint that can optionally crash for RCA testing."""
    if crash:
        return JSONResponse(
            status_code=500,
            content={
                "error": "InternalServerError",
                "message": "DatabaseDeadlockException: Failed to acquire lock on ledger_balances table."
            }
        )
    return {"status": "success", "tx_id": "TXN-998241", "amount": 500}
